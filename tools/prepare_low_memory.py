"""Derive the LowMemory icon atlas without altering the HD source.

Discard only transparent bottom rows, retain sprite IDs/UV coordinate space,
and halve both texture dimensions. Pillow is needed only for regeneration.
"""
from pathlib import Path
import argparse,hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/low-memory'

def emit(meta):
    code='// Generated by tools/prepare_low_memory.py; HD sprite coordinates remain unchanged.\n'
    for key in ['source_width','source_height','cropped_height','width','height','bytes']:
        code+=f'pub const {key.upper()}:usize={meta[key]};\n'
    (ROOT/'src/atlas_low_memory.rs').write_text(code,encoding='utf-8')

def prepare(check=False):
    source=ROOT/'assets/wishlist-atlas.rgba';data=source.read_bytes()
    rectangles=[tuple(map(int,m)) for m in re.findall(r'Sprite\{x:(\d+),y:(\d+),w:(\d+),h:(\d+)\}',(ROOT/'src/icons_generated.rs').read_text())]
    assert rectangles and len(data)==2048*1024*4
    assert all(x>=0 and y>=0 and x+w<=2048 and y+h<=1024 for x,y,w,h in rectangles)
    occupied=max(y+h for x,y,w,h in rectangles)
    cropped=(occupied+1+3)//4*4 # one transparent guard row, aligned for exact half-size
    assert cropped<=1024 and not any(data[cropped*2048*4+3::4]),'Cropping would discard visible pixels'
    stamp=hashlib.sha256(data+json.dumps(rectangles).encode()+Path(__file__).read_text(encoding='utf-8-sig').encode()).hexdigest()
    manifest=OUT/'manifest.json';target=OUT/'wishlist-atlas.rgba'
    old=json.loads(manifest.read_text()) if manifest.exists() else {}
    if old.get('source_sha256')==stamp and target.exists() and hashlib.sha256(target.read_bytes()).hexdigest()==old.get('sha256'):
        emit(old);print('LowMemory atlas verified:',old['width'],'x',old['height'],';',old['bytes'],'bytes');return old
    if check:raise SystemExit('LowMemory atlas is stale or corrupt. Regenerate with Python + Pillow.')
    try:from PIL import Image
    except ImportError:raise SystemExit('Generating LowMemory icons requires Pillow. Use Build.ps1 -ResourcePython with a Python interpreter that has Pillow installed.')
    image=Image.frombytes('RGBA',(2048,1024),data).crop((0,0,2048,cropped))
    reduced=image.resize((1024,cropped//2),Image.Resampling.LANCZOS)
    OUT.mkdir(exist_ok=True);target.write_bytes(reduced.tobytes())
    meta={'profile':'LowMemory','source_sha256':stamp,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'source_width':2048,'source_height':1024,'cropped_height':cropped,'width':1024,'height':cropped//2,'bytes':len(reduced.tobytes()),'sprites':len(rectangles)}
    manifest.write_text(json.dumps(meta,indent=2),encoding='utf-8');emit(meta)
    print('LowMemory atlas generated:',meta['width'],'x',meta['height'],';',meta['bytes'],'bytes')
    return meta

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();prepare(args.check)
