"""Crop only unused transparent rows from the HD atlas, preserving every sprite byte."""
from pathlib import Path
import argparse, hashlib, json, re
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/hd'

def prepare(check=False):
    source=(ROOT/'assets/wishlist-atlas.rgba').read_bytes()
    sprites=[tuple(map(int,m)) for m in re.findall(r'Sprite\{x:(\d+),y:(\d+),w:(\d+),h:(\d+)\}',(ROOT/'src/icons_generated.rs').read_text())]
    assert len(source)==2048*1024*4 and sprites
    assert all(0<=x and 0<=y and w>0 and h>0 and x+w<=2048 and y+h<=1024 for x,y,w,h in sprites)
    bottom=max(y+h for x,y,w,h in sprites)
    height=(bottom+1+3)//4*4
    assert height<=1024 and not any(source[height*2048*4+3::4]),'Would remove visible pixels'
    data=source[:height*2048*4]
    meta={'profile':'HD','source_sha256':hashlib.sha256(source).hexdigest(),'width':2048,'height':height,'bytes':len(data),'sprites':len(sprites),'sha256':hashlib.sha256(data).hexdigest()}
    target=OUT/'wishlist-atlas.rgba';manifest=OUT/'manifest.json'
    current=target.exists() and manifest.exists() and target.read_bytes()==data and json.loads(manifest.read_text())==meta
    if not current:
        if check:raise SystemExit('HD cropped atlas is stale or corrupt; run tools/prepare_hd_atlas.py.')
        OUT.mkdir(exist_ok=True);target.write_bytes(data);manifest.write_text(json.dumps(meta,indent=2),encoding='utf-8')
    # Coordinates stay unchanged: only the V denominator changes from 1024 to height.
    code='// Generated by tools/prepare_hd_atlas.py. Sprite coordinates and pixels are unchanged.\n'
    for key in ['width','height','bytes']:code+=f'pub const {key.upper()}:usize={meta[key]};\n'
    generated=ROOT/'src/atlas_hd.rs'
    if check:
        assert generated.exists() and generated.read_text()==code,'HD atlas constants are stale'
    else:generated.write_text(code,encoding='utf-8')
    print(f'HD cropped atlas verified: {meta["width"]} x {height}; {len(data)} bytes; {len(sprites)} unchanged sprites')
    return meta

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');prepare(parser.parse_args().check)
